"""Render the reviewed sbatch script for a Journal Studio Fluent draft.

Uses the Jobs template types and renderer from ``hpc_gui.plugins.job_templates``
so validation and substitution match plugin-delivered job templates. Values
are allowlisted by ``slurm_draft_inputs`` before they reach this module; path
values are additionally shell-quoted here.
"""

from __future__ import annotations

import shlex

from hpc_gui import __version__
from hpc_gui.journal_studio.slurm_draft_inputs import ResolvedDraft
from hpc_gui.plugins.job_templates import JobTemplate, TemplateVariable, render_template

DRAFT_TEMPLATE_ID = "journal-studio-fluent-draft"
DRAFT_PLUGIN_ID = "hpc_gui.journal_studio"

_TEMPLATE = """\
#!/bin/bash
# DRAFT generated by Journal Studio. Review it, then submit through the Jobs view only.
# Journal SHA-256: {{journal_sha256}}
#SBATCH --job-name={{job_name}}
#SBATCH --partition={{partition}}
#SBATCH --account={{account}}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task={{cpus_per_task}}
#SBATCH --time={{walltime}}
#SBATCH --output={{workdir}}/%x_%j.out
#SBATCH --error={{workdir}}/%x_%j.err

set -euo pipefail
cd -- {{workdir_q}}
FLUENT_BIN="${FLUENT_BIN:-$HOME/ansys/ansys_inc/{{fluent_bin_dir}}/fluent/bin/fluent}"
"$FLUENT_BIN" {{fluent_mode}} -g -t{{cpus_per_task}} -mpi=intel -i {{journal_q}}
"""

_VARIABLE_NAMES = (
    "job_name",
    "partition",
    "account",
    "cpus_per_task",
    "walltime",
    "workdir",
    "workdir_q",
    "journal_q",
    "journal_sha256",
    "fluent_bin_dir",
    "fluent_mode",
)


def draft_template() -> JobTemplate:
    """In-memory Jobs template describing the Journal Studio Fluent draft."""
    variables = tuple(
        TemplateVariable(name=name, type="integer", required=True, minimum=1, maximum=128)
        if name == "cpus_per_task"
        else TemplateVariable(name=name, type="string", required=True)
        for name in _VARIABLE_NAMES
    )
    return JobTemplate(
        id=DRAFT_TEMPLATE_ID,
        name="Journal Studio Fluent draft",
        scheduler="slurm",
        plugin_id=DRAFT_PLUGIN_ID,
        plugin_version=__version__,
        file_name="journal_studio.slurm",
        application="fluent",
        variables=variables,
        content=_TEMPLATE,
    )


def render_draft_script(resolved: ResolvedDraft, *, journal_sha256: str) -> str:
    """Return sbatch script text for *resolved*; pure text, nothing is executed."""
    if len(journal_sha256) != 64 or any(char not in "0123456789abcdef" for char in journal_sha256):
        raise ValueError("journal_sha256 must be a lowercase hex SHA-256 digest")
    values = {
        "job_name": resolved.job_name,
        "partition": resolved.partition,
        "account": resolved.account,
        "cpus_per_task": resolved.cpus_per_task,
        "walltime": resolved.walltime,
        "workdir": resolved.workdir,
        "workdir_q": shlex.quote(resolved.workdir),
        "journal_q": shlex.quote(resolved.journal_path),
        "journal_sha256": journal_sha256,
        "fluent_bin_dir": resolved.fluent_bin_dir,
        "fluent_mode": resolved.fluent_mode,
    }
    return render_template(draft_template(), values)
