"""wx widget construction for the OpenFOAM Case Studio page."""
from __future__ import annotations

from hpc_gui.core.i18n import t
from hpc_gui.openfoam_core.release_support import supported_releases


class WxCaseStudioView:
    def _build(self):
        wx = self.wx
        outer = wx.BoxSizer(wx.VERTICAL)
        toolbar = wx.WrapSizer(wx.HORIZONTAL)
        self.new_button = wx.Button(self.panel, label=t("openfoam.new_case"))
        self.open_button = wx.Button(self.panel, label=t("openfoam.open_case"))
        self.snapshot_button = wx.Button(self.panel, label=t("openfoam.open_snapshot"))
        self.save_button = wx.Button(self.panel, label=t("openfoam.save_case"))
        self.recover_button = wx.Button(self.panel, label=t("openfoam.recover_save"))
        self.recover_button.Disable()
        self.validate_button = wx.Button(self.panel, label=t("openfoam.validate"))
        self.allrun_button = wx.Button(self.panel, label=t("openfoam.create_allrun"))
        self.undo_button = wx.Button(self.panel, label=t("openfoam.undo"))
        self.redo_button = wx.Button(self.panel, label=t("openfoam.redo"))
        for button in (self.new_button, self.open_button, self.snapshot_button, self.save_button, self.recover_button, self.validate_button, self.allrun_button, self.undo_button, self.redo_button):
            toolbar.Add(button, 0, wx.ALL, 3)
        self.product = wx.Choice(self.panel, choices=["OpenFOAM.com / ESI"])
        self.product.SetSelection(0)
        self.product.Enable(False)
        self.version = wx.Choice(self.panel, choices=list(supported_releases()))
        self.version.SetSelection(0)
        self.version.Enable(True)
        toolbar.Add(wx.StaticText(self.panel, label=t("openfoam.edition")), 0, wx.ALIGN_CENTER_VERTICAL | wx.LEFT, 8)
        toolbar.Add(self.product, 0, wx.ALL, 3)
        toolbar.Add(self.version, 0, wx.ALL, 3)
        outer.Add(toolbar, 0, wx.EXPAND)

        self.status = wx.StaticText(self.panel, label=t("openfoam.no_case"))
        outer.Add(self.status, 0, wx.EXPAND | wx.LEFT | wx.RIGHT, 6)
        main = wx.SplitterWindow(self.panel, style=wx.SP_LIVE_UPDATE)
        left = wx.Panel(main)
        left_sizer = wx.BoxSizer(wx.VERTICAL)
        left_sizer.Add(wx.StaticText(left, label=t("openfoam.case_structure")), 0, wx.ALL, 5)
        left_sizer.Add(wx.StaticText(left, label=t("openfoam.search_case")), 0, wx.LEFT | wx.RIGHT | wx.TOP, 5)
        self.case_search = wx.SearchCtrl(left)
        left_sizer.Add(self.case_search, 0, wx.EXPAND | wx.ALL, 4)
        self.case_search_results = wx.ListBox(left)
        self.case_search_results.SetMinSize((-1, 90))
        left_sizer.Add(self.case_search_results, 0, wx.EXPAND | wx.LEFT | wx.RIGHT | wx.BOTTOM, 4)
        self.tree = wx.TreeCtrl(left, style=wx.TR_DEFAULT_STYLE)
        left_sizer.Add(self.tree, 1, wx.EXPAND | wx.ALL, 4)
        left.SetSizer(left_sizer)

        body = wx.SplitterWindow(main, style=wx.SP_LIVE_UPDATE)
        center = wx.Panel(body)
        center_sizer = wx.BoxSizer(wx.VERTICAL)
        center_sizer.Add(wx.StaticText(center, label=t("openfoam.visual_flow")), 0, wx.ALL, 5)
        self.flow = wx.ListBox(center)
        center_sizer.Add(self.flow, 1, wx.EXPAND | wx.ALL, 4)
        flow_actions = wx.BoxSizer(wx.HORIZONTAL)
        self.move_step_up = wx.Button(center, label=t("openfoam.move_workflow_up"))
        self.move_step_down = wx.Button(center, label=t("openfoam.move_workflow_down"))
        self.remove_step = wx.Button(center, label=t("openfoam.remove_workflow_step"))
        for button in (self.move_step_up, self.move_step_down, self.remove_step):
            flow_actions.Add(button, 0, wx.ALL, 3)
        center_sizer.Add(flow_actions, 0, wx.ALIGN_RIGHT)
        center_sizer.Add(wx.StaticText(center, label=t("openfoam.workflow_drag_hint")), 0, wx.LEFT | wx.RIGHT | wx.BOTTOM, 5)
        self.bottom = wx.Notebook(center)
        self.source_tabs = wx.Notebook(self.bottom)
        self.problems = wx.ListBox(self.bottom)
        self.diff = wx.TextCtrl(self.bottom, style=wx.TE_MULTILINE | wx.TE_READONLY | wx.HSCROLL)
        self.validation = wx.TextCtrl(self.bottom, style=wx.TE_MULTILINE | wx.TE_READONLY | wx.HSCROLL)
        self.preview = wx.TextCtrl(self.bottom, style=wx.TE_MULTILINE | wx.TE_READONLY | wx.HSCROLL)
        self.bottom.AddPage(self.source_tabs, t("openfoam.source"))
        self.bottom.AddPage(self.problems, t("openfoam.problems"))
        self.bottom.AddPage(self.diff, t("openfoam.diff"))
        self.bottom.AddPage(self.validation, t("openfoam.validation"))
        self.bottom.AddPage(self.preview, t("openfoam.case_preview"))
        center_sizer.Add(self.bottom, 2, wx.EXPAND | wx.ALL, 4)
        center.SetSizer(center_sizer)

        right = wx.Panel(body)
        right_sizer = wx.BoxSizer(wx.VERTICAL)
        right_sizer.Add(wx.StaticText(right, label=t("openfoam.command_library")), 0, wx.ALL, 5)
        self.command_filter = wx.SearchCtrl(right)
        right_sizer.Add(self.command_filter, 0, wx.EXPAND | wx.ALL, 4)
        self.commands = wx.ListBox(right)
        right_sizer.Add(self.commands, 1, wx.EXPAND | wx.ALL, 4)
        self.add_step = wx.Button(right, label=t("openfoam.add_workflow_step"))
        right_sizer.Add(self.add_step, 0, wx.EXPAND | wx.ALL, 3)
        right_sizer.Add(wx.StaticText(right, label=t("openfoam.inspector")), 0, wx.ALL, 5)
        self.command_details = wx.TextCtrl(right, style=wx.TE_MULTILINE | wx.TE_READONLY)
        right_sizer.Add(self.command_details, 1, wx.EXPAND | wx.ALL, 4)
        self.key_list = wx.ListBox(right)
        right_sizer.Add(self.key_list, 1, wx.EXPAND | wx.ALL, 4)
        self.parameter_type = wx.StaticText(right, label=t("openfoam.parameter_type_unknown"))
        right_sizer.Add(self.parameter_type, 0, wx.EXPAND | wx.LEFT | wx.RIGHT, 4)
        self.value_editor_panel = wx.Panel(right)
        self.value_editor_sizer = wx.BoxSizer(wx.VERTICAL)
        self.value_editor_panel.SetSizer(self.value_editor_sizer)
        right_sizer.Add(self.value_editor_panel, 0, wx.EXPAND | wx.ALL, 2)
        self.apply_value = wx.Button(right, label=t("openfoam.apply_parameter"))
        right_sizer.Add(self.apply_value, 0, wx.EXPAND | wx.ALL, 3)
        right.SetSizer(right_sizer)
        body.SplitVertically(center, right, -360)
        main.SplitVertically(left, body, 250)
        outer.Add(main, 1, wx.EXPAND | wx.ALL, 4)
        self.panel.SetSizer(outer)

        self.save_button.Bind(wx.EVT_BUTTON, self._save)
        self.recover_button.Bind(wx.EVT_BUTTON, self._recover_save)
        self.validate_button.Bind(wx.EVT_BUTTON, self._validate)
        self.allrun_button.Bind(wx.EVT_BUTTON, self._create_allrun)
        self.undo_button.Bind(wx.EVT_BUTTON, lambda _event: self._edit_command("Undo"))
        self.redo_button.Bind(wx.EVT_BUTTON, lambda _event: self._edit_command("Redo"))
        self.tree.Bind(wx.EVT_TREE_SEL_CHANGED, self._tree_selected)
        self.panel.SetDropTarget(self._drop_target())
