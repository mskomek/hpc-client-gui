"""Render an OpenFOAM case-local Allrun script from a reviewed workflow."""
from __future__ import annotations

import re
from collections.abc import Iterable, Mapping
from itertools import islice


_SAFE_COMMAND = re.compile(r"[A-Za-z][A-Za-z0-9_]*\Z")
_PREPROCESSORS = {"blockMesh", "checkMesh", "splitMeshRegions", "decomposePar"}
_POSTPROCESSORS = {"reconstructPar", "postProcess"}
_MAX_STEPS = 128


def render_allrun(solver: str, steps: Iterable[str], commands: Iterable[Mapping[str, object]]) -> str:
    """Return a draft-only Allrun that the Slurm wrapper can execute with bash."""
    definitions = {str(item.get("name")): dict(item) for item in commands}
    solver_definition = definitions.get(solver)
    if (
        not _SAFE_COMMAND.fullmatch(solver)
        or solver_definition is None
        or solver_definition.get("category") != "Solver"
    ):
        raise ValueError("solver is not in the approved OpenFOAM command catalog")

    ordered = list(islice(iter(steps), _MAX_STEPS + 1))
    if len(ordered) > _MAX_STEPS:
        raise ValueError(f"workflow exceeds the {_MAX_STEPS}-step draft limit")
    if solver not in ordered:
        ordered.append(solver)
    if ordered.count(solver) != 1:
        raise ValueError("workflow must contain the selected solver exactly once")

    solver_seen = False
    for name in ordered:
        if not _SAFE_COMMAND.fullmatch(name) or name not in definitions:
            raise ValueError("workflow contains a command outside the approved catalog")
        if definitions[name].get("category") == "Solver" and name != solver:
            raise ValueError("workflow contains a second solver")
        if name in _PREPROCESSORS and solver_seen:
            raise ValueError("mesh preparation steps must come before the solver")
        if name in _POSTPROCESSORS and not solver_seen:
            raise ValueError("post-processing steps must come after the solver")
        if name == solver:
            solver_seen = True

    lines = [
        "#!/usr/bin/env bash",
        "# Generated by OpenFOAM Case Studio. Load the OpenFOAM environment before running.",
        "set -euo pipefail",
        'cd -- "$(dirname -- "${BASH_SOURCE[0]}")"',
        "",
        f"solver={solver}",
        'nprocs="${SLURM_NTASKS:-1}"',
        'if [[ ! "$nprocs" =~ ^[1-9][0-9]*$ ]]; then',
        '    echo "SLURM_NTASKS must be a positive integer" >&2',
        "    exit 2",
        "fi",
        "",
    ]
    explicit_reconstruction = "reconstructPar" in ordered
    for name in ordered:
        if name == solver:
            lines.extend(_solver_lines(solver, automatic_reconstruction=not explicit_reconstruction))
        elif name == "decomposePar":
            lines.extend([
                'if (( nprocs > 1 )); then',
                "    decomposePar -force",
                "fi",
                "",
            ])
        elif name == "reconstructPar":
            lines.extend([
                'if (( nprocs > 1 )); then',
                "    reconstructPar -latestTime",
                "fi",
                "",
            ])
        else:
            lines.extend([f"{name}", ""])
    return "\n".join(lines)


def _solver_lines(solver: str, *, automatic_reconstruction: bool) -> list[str]:
    lines = [
        'if (( nprocs > 1 )); then',
        '    if [[ ! -d processor0 ]]; then',
        "        decomposePar",
        "    fi",
        '    mpirun -np "$nprocs" "$solver" -parallel',
    ]
    if automatic_reconstruction:
        lines.append("    reconstructPar -latestTime")
    lines.extend([
        "else",
        '    "$solver"',
        "fi",
        "",
    ])
    return lines
